# homeassistant.helpers.template
# ---------------------------------------------------------------------------

class Template:
    def __init__(self, template, hass=None):
        self.template = template
        self.hass = hass

    def async_render(self, parse_result: bool = False):
        return True

    def __eq__(self, other):
        return isinstance(other, Template) and other.template == self.template

    def __repr__(self):
        return f"Template({self.template!r})"


ha_helpers_template = _new_module("homeassistant.helpers.template")
ha_helpers_template.Template = Template


