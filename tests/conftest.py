"""Minimal Home Assistant stand-ins.

The real `homeassistant` PyPI package pulls in native-compiled dependencies
(pyspeex-noise, ciso8601, ...) that are unavailable in a plain dev environment
without a C build toolchain. Since this project only touches a small, stable
slice of the HA API, we provide lightweight real classes/modules for that
slice instead of installing the real package.

Unlike a bare `unittest.mock.MagicMock`, using real `types.ModuleType`
instances with explicitly-wired attributes avoids the classic pitfall where
`from homeassistant import config_entries` (or similar "from package import
submodule" statements) silently returns an autogenerated MagicMock
attribute instead of the submodule we registered in sys.modules.

Loaded automatically by pytest before any test module is collected.
"""
import sys
import types
from datetime import datetime, timezone
from enum import IntFlag
from unittest.mock import MagicMock

import voluptuous as vol


def _new_module(name: str) -> types.ModuleType:
    mod = types.ModuleType(name)
    sys.modules[name] = mod
    return mod


