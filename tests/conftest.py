# homeassistant.helpers.entity — bare-bones Entity base
# ---------------------------------------------------------------------------

class Entity:
    hass = None
    entity_id = None

    def async_write_ha_state(self):
        pass

    def async_schedule_update_ha_state(self, force_refresh: bool = False):
        pass

    def async_on_remove(self, func):
        if not hasattr(self, "_remove_callbacks"):
            self._remove_callbacks = []
        self._remove_callbacks.append(func)


